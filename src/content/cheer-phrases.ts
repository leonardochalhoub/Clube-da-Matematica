/** Per-locale cheer arrays. */
export const CHEERS_BY_LOCALE: Partial<Record<string, Cheer[]>> = {
  'pt-BR': CHEERS_PT,
  en: CHEERS_EN,
  es: CHEERS_ES,
}

/**
 * Pick the cheer array for the active locale. Falls back to CHEERS_PT
 * if the locale's array is missing OR empty (so a half-filled translation
 * pass doesn't crash CheerBanner).
 */
export function getCheers(locale: string): Cheer[] {
  const arr = CHEERS_BY_LOCALE[locale]
  return arr && arr.length > 0 ? arr : CHEERS_PT
}

